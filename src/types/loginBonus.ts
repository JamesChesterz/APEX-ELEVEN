/**
 * ระบบรางวัลล็อกอิน — รายสัปดาห์ (7 วัน) และรายเดือน (สะสมทั้งเดือน)
 *
 * กติกา:
 *   - เข้าเกมวันไหน กดรับได้ 1 ช่องของแต่ละปฏิทินในวันนั้น
 *   - ปฏิทินรายสัปดาห์รีเซ็ตทุกวันจันทร์ · รายเดือนรีเซ็ตวันที่ 1
 *   - รางวัลของทุกช่องตั้งจากหน้า ADMIN ได้ทั้งหมด (ใช้ชนิด GameReward กลาง)
 *
 * ⚠️ รายเดือนนับ "จำนวนวันที่เข้ามาในเดือนนั้น" ไม่ใช่วันที่ของเดือน
 * คนที่เริ่มเล่นกลางเดือนจึงยังไล่เก็บรางวัลตั้งแต่ช่องแรกได้ ไม่ใช่โดนข้ามไปครึ่งปฏิทิน
 */
import type { GameReward } from './reward';

/** จำนวนช่องของปฏิทินรายสัปดาห์ */
export const WEEKLY_DAYS = 7;

/** จำนวนช่องของปฏิทินรายเดือน */
export const MONTHLY_DAYS = 30;

export interface LoginBonusConfig {
  /** false = ซ่อนเมนูนี้จากผู้เล่นทั้งหมด */
  enabled: boolean;
  /** หัวข้อที่โชว์บนหน้า */
  title: string;
  /** รางวัล 7 ช่องของปฏิทินรายสัปดาห์ */
  weekly: GameReward[];
  /** รางวัล 30 ช่องของปฏิทินรายเดือน */
  monthly: GameReward[];
}

/** ความคืบหน้าของผู้เล่นหนึ่งคน (เก็บลงบัญชี) */
export interface LoginBonusState {
  /** สัปดาห์ที่ตัวเลขชุดนี้เป็นของ เช่น '2026-W36' — ไม่ตรง = เริ่มนับใหม่ */
  weekKey: string;
  /** ช่องรายสัปดาห์ที่กดรับไปแล้ว (0-based) */
  weeklyClaimed: number[];
  /** เดือนที่ตัวเลขชุดนี้เป็นของ เช่น '2026-09' */
  monthKey: string;
  /** ช่องรายเดือนที่กดรับไปแล้ว (0-based) */
  monthlyClaimed: number[];
  /** วันที่กดรับล่าสุดของแต่ละปฏิทิน (YYYY-MM-DD) — กันกดซ้ำในวันเดียว */
  lastWeeklyDate?: string;
  lastMonthlyDate?: string;
}
