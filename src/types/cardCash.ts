/**
 * ระบบ "แลกการ์ดเป็นเงิน" — ขายนักเตะที่ไม่ใช้แล้วเป็นเหรียญ (BP)
 *
 * ต่างจากระบบย่อยการ์ดเดิม (services/salvage.ts) ที่ให้ "แต้มแลกนักเตะ"
 * ระบบนี้ให้ "เงิน" และมีเพดานรายวันคุมไม่ให้เศรษฐกิจในเกมพัง
 * ทั้งสองระบบอยู่ด้วยกันได้ ผู้เล่นเลือกเองว่าจะแลกเป็นแต้มหรือเป็นเงิน
 */

/** ค่าตั้งที่แอดมินปรับได้ (config/cardCash) */
export interface CardCashConfig {
  /** false = ปิดระบบ ซ่อนเมนูจากผู้เล่น */
  enabled: boolean;
  /** เพดานเงินที่แลกได้ต่อวันต่อบัญชี */
  dailyLimit: number;
  /**
   * ตัวคูณราคาทั้งระบบ (1 = ราคามาตรฐาน)
   * ใช้ปรับเศรษฐกิจทั้งเกมได้โดยไม่ต้องแก้สูตรทีละระดับ
   */
  rate: number;
  /** เลือกแลกพร้อมกันได้สูงสุดกี่ใบต่อครั้ง */
  maxPerExchange: number;
}

/** ความคืบหน้าของผู้เล่นหนึ่งคน (เก็บลงบัญชี) */
export interface CardCashState {
  /** วันที่ของยอดนี้ (YYYY-MM-DD) — คนละวัน = เริ่มนับใหม่ */
  date: string;
  /** เงินที่แลกไปแล้ววันนี้ */
  earned: number;
}
