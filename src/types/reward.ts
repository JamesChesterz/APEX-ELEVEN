/**
 * "รางวัล" หนึ่งชิ้นแบบกลางของทั้งเกม
 *
 * ก่อนหน้านี้แต่ละระบบมีชนิดรางวัลของตัวเอง (LuckyReward · PassReward)
 * พอเพิ่มของใหม่ทีต้องไล่แก้ทุกไฟล์ ชนิดนี้จึงถูกออกแบบให้ครอบทุกอย่างที่มีในเกม
 * แล้วให้ระบบใหม่ ๆ (ล็อกอินรายวัน · ของขวัญแอดมิน) ใช้ตัวเดียวกัน
 *
 * ⚠️ จุดสำคัญของการรองรับอนาคต: ไอเทมไม่ได้แยกเป็น kind ละชนิด
 * แต่ใช้ kind = 'item' + itemId ชี้ไปที่ทะเบียนไอเทม (services/rewards.ts)
 * เพิ่มไอเทมใหม่ในเกมจึงแก้ที่ทะเบียนที่เดียว ไม่ต้องแตะชนิดข้อมูลหรือหน้าจอไหนเลย
 */

/** ประเภทของรางวัล */
export type RewardKind =
  | 'coins'
  | 'points'
  | 'upgradePoints'
  | 'passTicket'
  /** ไอเทมในคลัง — ระบุตัวไอเทมด้วย itemId */
  | 'item'
  /** การ์ดนักเตะ — ระบุด้วย playerId */
  | 'card';

export interface GameReward {
  kind: RewardKind;
  /** จำนวนที่ได้รับ (ค่าเริ่มต้น 1) */
  amount?: number;
  /** ใช้กับ kind = 'item' — รหัสไอเทมในทะเบียน */
  itemId?: string;
  /** ใช้กับ kind = 'card' — id นักเตะ */
  playerId?: string;
  /** ค่าตีบวกของการ์ดที่แจก (0 = ปกติ) */
  upgrade?: number;
  /** รูปที่จะโชว์แทนไอคอนประจำประเภท (พาธใน public/ หรือ data URL) */
  image?: string;
}
