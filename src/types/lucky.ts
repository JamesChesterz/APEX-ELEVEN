/**
 * โครงสร้างข้อมูลของ "กล่องสุ่มรางวัลแบบตาราง" (เมนู Lucky Box ใต้ Exchange)
 *
 * ขนาดตารางแอดมินตั้งเองได้ (คอลัมน์ × แถว) ค่าตั้งต้นคือ 8×8
 * กลางตารางถูกจองไว้ให้การ์ดใหญ่ใบเดียว (การ์ด MYTHICAL) เสมอ
 * ด้านที่เป็นเลขคู่จะจองกว้าง 2 ช่อง ด้านที่เป็นเลขคี่จองช่องเดียว
 * (8×8 → จอง 2×2 = 4 ช่อง เหลือช่องรางวัลปกติ 60 ช่อง · 7×7 → จอง 1 ช่อง เหลือ 48 ช่อง)
 *
 * กติกาเหมือนกล่องสุ่มในเกมมือถือทั่วไป: จ่ายเหรียญเพื่อสุ่มเปิดช่องที่ยังไม่เปิด
 * รางวัลแต่ละช่องได้ครั้งเดียว และราคาสุ่มแพงขึ้นเรื่อย ๆ ตามจำนวนครั้งที่สุ่มไปแล้ว
 */

/** ประเภทของรางวัลที่วางในช่องได้ */
export type LuckyRewardType = 'coins' | 'points' | 'upgradePoints' | 'card';

/** รางวัลหนึ่งช่อง */
export interface LuckyReward {
  type: LuckyRewardType;
  /** จำนวนที่ได้รับ — ใช้กับ coins / points / upgradePoints */
  amount?: number;
  /** id นักเตะที่จะได้รับ — ใช้กับ type = 'card' */
  playerId?: string;
}

/** ค่าตั้งกล่องสุ่มทั้งใบ (config/luckyGrid — แอดมินเป็นคนกำหนด) */
export interface LuckyGridConfig {
  /** false = ซ่อนเมนูนี้จากผู้เล่นทั้งหมด */
  enabled: boolean;
  /** ชื่อกล่องที่โชว์บนหัวหน้า เช่น "MYTHIC BOX" */
  title: string;
  /** ตารางกว้างกี่ช่อง (คอลัมน์) */
  columns: number;
  /** ตารางสูงกี่ช่อง (แถว) */
  rows: number;
  /** ราคาสุ่มครั้งแรกของรอบ (เหรียญ) */
  baseCost: number;
  /** ราคาบวกเพิ่มทุกครั้งที่สุ่มไปแล้วหนึ่งครั้ง */
  costStep: number;
  /** เพดานราคาต่อครั้ง (0 = ไม่จำกัด) */
  maxCost: number;
  /** การ์ดใหญ่กลางตาราง — ตั้งใจให้เป็นการ์ดระดับ MYTHICAL */
  grandPlayerId: string;
  /** รางวัลของช่องปกติทุกช่อง เรียงจากซ้ายไปขวา บนลงล่าง (ข้ามช่องกลางที่การ์ดใหญ่จองไว้) */
  cells: LuckyReward[];
  /** เวลาที่กล่องนี้ปิด (ISO) — ไม่ตั้ง = เปิดไปเรื่อย ๆ */
  endsAt?: string;
  /** true = เก็บครบทุกช่องแล้วเริ่มรอบใหม่ให้อัตโนมัติ (ราคาสุ่มกลับไปเริ่มต้น) */
  autoReset: boolean;
  /**
   * เลขรอบของกล่องใบนี้ แอดมินกด "เริ่มรอบใหม่" (หรือเปลี่ยนขนาดตาราง) เมื่อไหร่เลขนี้ +1
   * ความคืบหน้าของผู้เล่นที่ไม่ตรงเลขรอบ จะถูกล้างทิ้งอัตโนมัติ
   */
  round: number;
}

/** ความคืบหน้าของผู้เล่นหนึ่งคนในกล่องใบนี้ (เก็บลงบัญชี) */
export interface LuckyGridState {
  /** รอบของกล่องที่ตัวเลขชุดนี้เป็นของ — ไม่ตรงกับ config = เริ่มนับใหม่ */
  round: number;
  /** ช่องที่เปิดไปแล้ว (0 ถึง cellCount−1 = ช่องปกติ, cellCount = การ์ดใหญ่กลางตาราง) */
  opened: number[];
  /** สุ่มไปแล้วกี่ครั้งในรอบนี้ — ใช้คิดราคาสุ่มครั้งถัดไป */
  draws: number;
}
