/**
 * ทีมจำลองประจำเซิร์ฟเวอร์ ("fake player")
 *
 * แนวคิด: ไม่เก็บค่าปัจจุบันของบอทไว้ที่ไหนเลย — ทั้ง OVR และคะแนนคำนวณสด
 * จาก "เมล็ดพันธุ์" (BotSeed) + เวลาปัจจุบัน ทุกเครื่องจึงได้ค่าเดียวกันเป๊ะ
 * โดยไม่ต้องมีเซิร์ฟเวอร์คอยอัปเดต (โปรเจกต์นี้ยังไม่มี Cloud Functions ใช้)
 *
 * แอดมินแทรกแซงได้สองชั้น:
 *   1. BotConfig   — ค่าตั้งรวมของทั้งระบบ (จำนวนบอท ช่วงค่าพลัง เพดานคะแนน)
 *   2. BotOverride — ล็อกค่าของบอทรายตัว (ค่าพลัง ตีบวก คะแนน ชื่อ)
 * ทั้งสองเก็บในเอกสาร config/bots บน Firestore (ADMIN → ทีมจำลอง)
 */

/** ค่าคงที่ประจำตัวบอทหนึ่งทีม — งอกจาก seed เดียว แล้วแอดมินทับได้ทีหลัง */
export interface BotSeed {
  id: string;
  teamName: string;
  managerName: string;
  /** เลข seed ของ PRNG — ทุกค่าสุ่มของบอทตัวนี้งอกมาจากตัวเลขนี้ */
  seed: number;
  /** ค่าพลังทีมตอนเพิ่งตั้งทีม */
  baseOvr: number;
  /** เพดานค่าพลังที่บอทตัวนี้ไปได้ (คนละเพดานกันจึงไม่โตไล่กันเป็นแถว) */
  capOvr: number;
  /** ค่าคงที่เวลาของเส้นโค้งการโต (วัน) — ยิ่งน้อยยิ่งโตเร็วแล้วตัน */
  growthDays: number;
  /** ตั้งทีมมาแล้วกี่วันนับถึงวัน EPOCH (บางทีมเก่า บางทีมเพิ่งมา) */
  ageDays: number;
  /** ลงแข่งเฉลี่ยกี่นัดต่อวัน */
  matchesPerDay: number;
  /** วันเริ่มรอบลาดเดอร์ของทีมนี้ — คนละวันกัน คะแนนทั้งตารางจึงไม่รีเซ็ตพร้อมกัน */
  cycleOffset: number;
  /** เฟสของคลื่นฟอร์ม (0–1) ทำให้แต่ละทีมฟอร์มขึ้น-ตกคนละจังหวะ */
  formPhase: number;
  /** อัตราชนะ/เสมอของบอทตัวนี้ ใช้แตกสถิติจากจำนวนนัดที่ลง */
  winRate: number;
  drawRate: number;
  /** ค่าตีบวกของทีม (+0 → +8) — บวกค่าพลังตามตารางตีบวกที่แอดมินตั้งไว้ */
  plus: number;
  /** ค่าพลังที่แอดมินล็อกไว้ (มีค่า = ไม่โตตามเวลาแล้ว) */
  lockedOvr?: number;
  /** คะแนนที่แอดมินล็อกไว้ (มีค่า = ไม่ขยับตามเวลาแล้ว) */
  lockedPoints?: number;
  /** true = แอดมินสั่งซ่อนออกจากตาราง */
  hidden?: boolean;
}

/**
 * ค่าที่แอดมินล็อกทับรายตัว (ADMIN → ทีมจำลอง)
 * ไม่ใส่ = ปล่อยให้ระบบสุ่มและโตเองตามปกติ
 */
export interface BotOverride {
  teamName?: string;
  managerName?: string;
  /** ล็อกค่าพลังตายตัว — ใส่แล้วทีมนี้จะไม่โตตามเวลาอีก */
  ovr?: number;
  /** เพดานค่าพลัง (ใช้ตอนยังปล่อยให้โตเอง) */
  capOvr?: number;
  /** ตีบวกของทีม +0 → +8 บวกทับค่าพลังที่คำนวณได้ */
  plus?: number;
  /** ลงแข่งกี่นัดต่อวัน — คุมความเร็วในการไต่อันดับ */
  matchesPerDay?: number;
  /** อัตราชนะ 0–1 */
  winRate?: number;
  /** ล็อกคะแนนตายตัว — ใส่แล้วคะแนนจะไม่ขยับตามเวลา */
  points?: number;
  /** ซ่อนทีมนี้ออกจากตารางโดยไม่ต้องลบค่าที่ตั้งไว้ */
  hidden?: boolean;
}

/** ค่าตั้งรวมของระบบทีมจำลอง (เอกสาร config/bots) */
export interface BotConfig {
  /** ปิดแล้วตารางอันดับจะเหลือแต่ผู้เล่นจริง */
  enabled: boolean;
  /** จำนวนบอททั้งเซิร์ฟเวอร์ */
  rosterSize: number;
  /** ความยาวตารางอันดับที่อยากให้เห็น (ผู้เล่นจริงมาก่อน เหลือเท่าไหร่บอทเติม) */
  tableRows: number;
  /**
   * จำนวนทีมจำลองที่ต้องขึ้นตารางเสมอ ไม่ว่าจะมีผู้เล่นจริงกี่คน
   * ถ้าไม่มีค่านี้ พอคนจริงเยอะกว่า tableRows บอทจะหายเกลี้ยงทั้งกระดาน
   */
  minBots: number;
  /** เพดานคะแนนบอทเทียบผู้เล่นจริงที่นำอยู่ (0–1) */
  topShare: number;
  /** คะแนนอ้างอิงขั้นต่ำตอนเซิร์ฟเวอร์ยังใหม่ */
  minAnchor: number;
  /** รอบรีเซ็ตคะแนนของบอท (วัน) */
  cycleDays: number;
  /** ช่วงค่าพลังตอนตั้งทีมของบอทที่ระบบสุ่มให้ */
  baseOvrMin: number;
  baseOvrMax: number;
  /** ช่วงเพดานค่าพลัง */
  capOvrMin: number;
  capOvrMax: number;
  /** ช่วงจำนวนนัดต่อวัน */
  matchesMin: number;
  matchesMax: number;
  /** ค่าที่แอดมินล็อกรายตัว (botId → ค่า) */
  overrides: Record<string, BotOverride>;
}

/** สภาพของบอท ณ เวลาหนึ่ง — คำนวณใหม่ทุกครั้ง ไม่ได้เก็บลงฐานข้อมูล */
export interface BotState {
  ovr: number;
  points: number;
  wins: number;
  draws: number;
  losses: number;
}
