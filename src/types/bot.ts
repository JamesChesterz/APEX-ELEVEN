/**
 * ทีมจำลองประจำเซิร์ฟเวอร์ ("fake player")
 *
 * แนวคิด: ไม่เก็บค่าปัจจุบันของบอทไว้ที่ไหนเลย — ทั้ง OVR และคะแนนคำนวณสด
 * จาก "เมล็ดพันธุ์" (BotSeed) + เวลาปัจจุบัน ทุกเครื่องจึงได้ค่าเดียวกันเป๊ะ
 * โดยไม่ต้องมีเซิร์ฟเวอร์คอยอัปเดต (โปรเจกต์นี้ยังไม่มี Cloud Functions ใช้)
 */

/** ค่าคงที่ประจำตัวบอทหนึ่งทีม — ไม่เปลี่ยนตลอดอายุโปรเจกต์ */
export interface BotSeed {
  id: string;
  teamName: string;
  managerName: string;
  /** เลข seed ของ PRNG — ทุกค่าสุ่มของบอทตัวนี้งอกมาจากตัวเลขนี้ */
  seed: number;
  /** ค่าพลังทีมตอนเพิ่งตั้งทีม */
  baseOvr: number;
  /** เพดานค่าพลังที่บอทตัวนี้ไปได้ (คนละเพดานกันจึงไม่โตไล่กันเป็นแถว) */
  capOvr: number;
  /** ค่าคงที่เวลาของเส้นโค้งการโต (วัน) — ยิ่งน้อยยิ่งโตเร็วแล้วตัน */
  growthDays: number;
  /** ตั้งทีมมาแล้วกี่วันนับถึงวัน EPOCH (บางทีมเก่า บางทีมเพิ่งมา) */
  ageDays: number;
  /** ลงแข่งเฉลี่ยกี่นัดต่อวัน */
  matchesPerDay: number;
  /** วันเริ่มรอบลาดเดอร์ของทีมนี้ — คนละวันกัน คะแนนทั้งตารางจึงไม่รีเซ็ตพร้อมกัน */
  cycleOffset: number;
  /** เฟสของคลื่นฟอร์ม (0–1) ทำให้แต่ละทีมฟอร์มขึ้น-ตกคนละจังหวะ */
  formPhase: number;
  /** อัตราชนะ/เสมอของบอทตัวนี้ ใช้แตกสถิติจากจำนวนนัดที่ลง */
  winRate: number;
  drawRate: number;
}

/** สภาพของบอท ณ เวลาหนึ่ง — คำนวณใหม่ทุกครั้ง ไม่ได้เก็บลงฐานข้อมูล */
export interface BotState {
  ovr: number;
  points: number;
  wins: number;
  draws: number;
  losses: number;
}
