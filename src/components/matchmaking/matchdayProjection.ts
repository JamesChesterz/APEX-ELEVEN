/**
 * แปลงพิกัดแผนการเล่น (x/y 0–100 ต่อทีม) เป็นตำแหน่งบนสนาม Matchmaking เดียวกัน
 *
 * ภาพพื้นหลัง (matchday.png) เป็นภาพสนามแบบ perspective จริง — ประตูฝั่งใกล้กล้อง (ซ้าย)
 * ใหญ่และห่างเส้นออกไปได้กว้าง ส่วนประตูฝั่งไกลกล้อง (ขวา) เล็กและเส้นบีบเข้าหากันตามระยะ
 * เหมือนภาพถ่ายมุมมองยาวตามสนามจริง (จุดหายไปอยู่ทางขวา) — ไม่ใช่ภาพตัดครึ่งแบบสมมาตร
 *
 * ค่าคงที่ด้านล่างถูกคาลิเบรตแยกต่างหากเฉพาะไฟล์นี้ (ไม่ใช้ TOP_SCALE ร่วมกับ MY TEAM)
 * เทียบกับตำแหน่งจริงบนภาพพื้นหลัง เพื่อไม่ให้กระทบระบบอื่นเวลาปรับจูนภายหลัง
 *
 *   home (ทีมเรา)      → ครองความลึกใกล้ 0% ของสนามทั้งผืน ประตูชิดขอบซ้ายสุด (ใกล้กล้อง ใหญ่)
 *   away (ทีมคู่แข่ง)   → พิกัด y กลับด้าน (100 − y) แล้วครองความลึกใกล้ 100% ประตูชิดขอบขวาสุด
 *                        (ไกลกล้อง เล็กกว่า) ทั้งสองฝั่งจึงมาบรรจบใกล้เส้นกลางสนาม
 *
 * ใช้สูตรเดียวกันทั้งสองฝั่ง (แค่ค่าความลึกตั้งต้นต่างกัน) ตำแหน่งจึงสมมาตรกันจริง
 */
import type { ProjectedPoint } from '@/components/pitch/FormationPositions';

/** ความเอียงของมุมกล้อง เฉพาะสนาม Matchmaking (ยิ่งน้อยยิ่งเอียงมาก บีบฝั่งไกลกล้องแรงขึ้น) */
const TOP_SCALE = 0.9;

/** เผื่อขอบซ้าย-ขวาไม่ให้การ์ดล้นออกนอกกรอบสนาม (ฝั่งใกล้กล้องเผื่อน้อยกว่าเพราะประตูใหญ่ชิดขอบจริง) */
const SAFE_LEFT = 8;
const SAFE_RIGHT = 10;
/** เผื่อขอบบน-ล่าง — ไม่เท่ากันเพราะแถบสกอร์/ม้านั่งสำรองด้านบนกินพื้นที่มากกว่าด้านล่าง */
const SAFE_TOP = 3;
const SAFE_BOTTOM = 16;

/** แต่ละทีมครองความลึกของสนามได้ไม่เกินนี้ (%) เว้นช่องตรงกลางไว้ให้เห็นเส้นกลางสนามชัด ๆ */
const HALF_DEPTH = 48;

export const projectMatchday = (
  x: number,
  y: number,
  side: 'home' | 'away',
): ProjectedPoint => {
  // ความลึกรวมทั้งสนาม (0 = ประตูเราริมซ้ายสุด ไปจนถึง 100 = ประตูคู่แข่งริมขวาสุด)
  const overallDepth = side === 'home' ? (y / 100) * HALF_DEPTH : 100 - (y / 100) * HALF_DEPTH;
  const depth = overallDepth / 100;

  // สูตร perspective: ยิ่งลึก (ไกลกล้อง) ยิ่งบีบเข้าหาเส้นขอบฟ้า
  const v = depth / (TOP_SCALE + (1 - TOP_SCALE) * depth);
  const scale = 1 - (1 - TOP_SCALE) * v;

  const screenX = SAFE_LEFT + v * (100 - SAFE_LEFT - SAFE_RIGHT);
  // กระจายแนวตั้งตามความกว้างเดิมของฟอร์เมชัน บีบแคบเข้าหากึ่งกลางเมื่อยิ่งไกลกล้อง (เหมือนเส้นข้างบีบตามระยะจริง)
  const spreadRaw = 50 + (x - 50) * scale;
  const screenY = SAFE_TOP + (spreadRaw / 100) * (100 - SAFE_TOP - SAFE_BOTTOM);

  return { x: screenX, y: screenY, scale };
};
